# Generate regs.py (register map of the board information peripheral for the host tools) from the
# csr.csv of a build:
#   ./sw/gen_regs.py build/sim/csr.csv > sw/regs.py

import sys
import csv

def main():
    regs, word_bits = {}, 32
    with open(sys.argv[1]) as f:
        for row in csv.reader(f):
            if not row or row[0].startswith("#"):
                continue
            if row[0] == "constant" and row[1] == "config_csr_data_width":
                word_bits = int(row[2])
            if row[0] == "csr_register" and row[1].startswith("info_"):
                regs[row[1][len("info_"):]] = (int(row[2], 0), int(row[3]))
    print("# Generated by sw/gen_regs.py, do not edit.")
    print()
    print(f"WORD_BITS = {word_bits}")
    print()
    print("REGS = {")
    for name, (address, words) in regs.items():
        key = f'"{name}"'
        print(f"    {key:12s} : (0x{address:08x}, {words}),")
    print("}")

if __name__ == "__main__":
    main()
