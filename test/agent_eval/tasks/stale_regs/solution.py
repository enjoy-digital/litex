# Reference solution: sw/regs.py was generated from a build with 32-bit CSRs, the SoC is now built
# with csr_data_width=8 (soc.json): every register spans several 8-bit words at other addresses.
# Regenerate regs.py for the current build (what ./sw/gen_regs.py build/sim/csr.csv produces).

import os

REGS = '''# Generated by sw/gen_regs.py, do not edit.

WORD_BITS = 8

REGS = {
    "id"         : (0x00001000, 4),
    "serial"     : (0x00001010, 8),
    "cal_gain"   : (0x00001030, 4),
    "cal_offset" : (0x00001040, 2),
    "scratch"    : (0x00001048, 4),
}
'''

def solve(workdir):
    with open(os.path.join(workdir, "sw", "regs.py"), "w") as f:
        f.write(REGS)
