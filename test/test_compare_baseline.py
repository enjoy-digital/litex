import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest


SCRIPT = Path(__file__).resolve().parents[1] / "scripts/compare_baseline.py"


class TestBaselineComparison(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.left = self.root / "reference"
        self.right = self.root / "candidate"
        self.output = self.root / "comparison.json"
        self.files = {
            "csr.json": '{"csr_bases":{"ctrl":0},"constants":{"width":32}}\n',
            "csr.csv": "#" + "-" * 80 + "\n# Auto-generated by LiteX (abc123) on 2026-09-28 10:00:00\n#" + "-" * 80 + "\ncsr_base,ctrl,0x00000000,,\n",
            "gateware/minimal_soc.v": """// -----------------------------------------------------------------------------
// Auto-Generated by:        LiteX
// logo
// logo
// logo
// logo
//                     Build your hardware, easily!
//                   https://github.com/enjoy-digital/litex
//
// Filename   : minimal_soc.v
// Top        : MinimalSoC
// Device     : baseline
// LiteX sha1 : abc123
// Date       : 2026-09-28 10:00:00
//------------------------------------------------------------------------------
module minimal_soc; wire [31:0] bus; endmodule
// -----------------------------------------------------------------------------
//  Auto-Generated by LiteX on 2026-09-28 10:00:00.
//------------------------------------------------------------------------------
""",
            "gateware/minimal_soc_mem.init": "4c\n69\n",
            "software/include/generated/csr.h": "#define CTRL_ADDR 0\n",
            "software/include/generated/soc.h": "#define CLOCK_FREQUENCY 1000000\n",
        }
        self.write_run(self.left, self.files)
        self.write_run(self.right, self.files)

    def write_run(self, root, files, frequency=1_000_000):
        artifacts = []
        for name, text in files.items():
            data = text if isinstance(text, bytes) else text.encode("utf-8")
            path = root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
            artifacts.append({"path": name, "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest()})
        (root / "baseline-summary.json").write_text(json.dumps({
            "build_name": "minimal_soc", "sys_clk_freq": frequency,
            "output_dir": str(root), "artifacts": artifacts,
        }), encoding="utf-8")

    def invoke(self, expected_exit):
        result = subprocess.run([sys.executable, str(SCRIPT), str(self.left), str(self.right),
                                 "--output", str(self.output)], capture_output=True, text=True)
        self.assertEqual(result.returncode, expected_exit, result.stdout + result.stderr)
        return json.loads(self.output.read_text(encoding="utf-8"))

    def test_json_key_order_banner_time_and_line_endings_can_differ(self):
        changed = {name: text.replace("\n", "\r\n").replace("10:00:00", "11:22:33")
                   for name, text in self.files.items()}
        changed["csr.json"] = '{"constants":{"width":32},"csr_bases":{"ctrl":0}}'
        self.write_run(self.right, changed)
        report = self.invoke(0)
        self.assertEqual(report["status"], "MATCH")
        self.assertTrue(any(item["status"] == "NORMALIZED_EQUAL" for item in report["files"]))

    def test_csr_address_change_is_a_difference(self):
        self.write_run(self.right, {**self.files, "csr.json": self.files["csr.json"].replace('"ctrl":0', '"ctrl":4')})
        self.assertEqual(self.invoke(1)["status"], "DIFFERENT")

    def test_hdl_logic_and_memory_changes_are_not_ignored(self):
        for name, replacement in [("gateware/minimal_soc.v", "module minimal_soc; endmodule\n"),
                                   ("gateware/minimal_soc_mem.init", "00\n00\n")]:
            with self.subTest(name=name):
                self.write_run(self.right, {**self.files, name: replacement})
                report = self.invoke(1)
                self.assertEqual(next(item for item in report["files"] if item["path"] == name)["status"], "DIFFERENT")

    def test_git_revision_is_not_a_timestamp(self):
        self.write_run(self.right, {**self.files, "csr.csv": self.files["csr.csv"].replace("abc123", "def456")})
        self.assertEqual(self.invoke(1)["status"], "DIFFERENT")

    def test_invalid_json_is_rejected_even_in_identical_files(self):
        for value in ['{"ctrl":0,"ctrl":4}', '{"ctrl":NaN}', b'\xff']:
            with self.subTest(value=value):
                files = {**self.files, "csr.json": value}
                self.write_run(self.left, files)
                self.write_run(self.right, files)
                self.assertEqual(self.invoke(2)["status"], "INVALID")

    def test_missing_required_file_on_both_sides_is_invalid(self):
        files = {name: text for name, text in self.files.items() if name != "csr.json"}
        for root in (self.left, self.right):
            (root / "csr.json").unlink()
            self.write_run(root, files)
        self.assertEqual(self.invoke(2)["status"], "INVALID")

    def test_modified_file_with_stale_manifest_is_invalid(self):
        (self.right / "csr.json").write_text('{"ctrl":4}', encoding="utf-8")
        self.assertEqual(self.invoke(2)["status"], "INVALID")

    def test_different_clock_configuration_does_not_match(self):
        self.write_run(self.right, self.files, frequency=2_000_000)
        self.assertEqual(self.invoke(1)["status"], "DIFFERENT")


if __name__ == "__main__":
    unittest.main()
