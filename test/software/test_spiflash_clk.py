import os
import subprocess
import textwrap

# Host harnesses for the clock frequency reports of liblitespi (spiflash.c, spiram.c).

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))


def _write(path, contents=""):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(textwrap.dedent(contents))


def _run(tmp_path, source):
    binary = tmp_path / "harness"
    subprocess.check_call([
        "gcc",
        "-std=gnu11",
        "-Wall",
        "-Wextra",
        "-Werror",
        "-Wno-unused-function",
        "-Wno-format",
        "-I", str(tmp_path / "include"),
        str(source),
        "-o", str(binary),
    ])
    return subprocess.check_output([str(binary)]).decode()


def test_spiflash_prints_khz_below_1mhz(tmp_path):
    include_dir = tmp_path / "include"
    _write(include_dir / "generated" / "csr.h", """
        #define CSR_SPIFLASH_BASE 1
    """)
    _write(include_dir / "generated" / "mem.h")
    _write(include_dir / "libbase" / "crc.h")
    _write(include_dir / "libbase" / "memtest.h")
    _write(include_dir / "system.h", """
        #define SPIFLASH_PHY_FREQUENCY 500000
        #define SPIFLASH_MODULE_NAME   "model"
    """)
    source = tmp_path / "harness.c"
    _write(source, f"""
        #include <stdbool.h>
        #include <stdint.h>
        #include "{REPO}/litex/soc/software/liblitespi/spiflash.c"

        int main(void)
        {{
            return spiflash_freq_init();
        }}
    """)
    assert _run(tmp_path, source) == "SPI Flash clk configured to 500 kHz\n"


def test_spiram_prints_clock_generator_frequency(tmp_path):
    include_dir = tmp_path / "include"
    _write(include_dir / "generated" / "csr.h", """
        #include <stdint.h>
        #define CSR_SPIRAM_BASE                1
        #define CSR_SPIRAM_PHY_CLK_DIVISOR_ADDR 1
        #define max(x, y) (((x) > (y)) ? (x) : (y))
        #define min(x, y) (((x) < (y)) ? (x) : (y))
        static inline uint32_t spiram_phy_clk_divisor_read(void) { return divisor; }
        static inline void spiram_phy_clk_divisor_write(uint32_t v) { divisor = v; }
        static inline void spiram_mmap_dummy_bits_write(uint32_t v) { (void)v; }
        static inline uint32_t spiram_mmap_dummy_bits_read(void) { return 0; }
    """)
    _write(include_dir / "generated" / "mem.h", """
        #define SPIRAM_BASE       0x1000UL
        #define SPIRAM_SIZE       0x1000
        #define SPIRAM_BLOCK_SIZE 0x100 /* Not generated by LiteX, needed by the divisor path. */
    """)
    _write(include_dir / "generated" / "soc.h")
    _write(include_dir / "libbase" / "memtest.h", """
        #include <stdbool.h>
        #include <stdint.h>
        #define MEMTEST_DATA_SIZE 0x1000
        static uint32_t divisor = 8;
        /* Data errors below divisor 3. */
        static inline int memtest_data(unsigned int *addr, unsigned long size, int random, void *s)
        {
            (void)addr; (void)size; (void)random; (void)s;
            return divisor < 3;
        }
        static inline void memspeed(unsigned int *addr, unsigned long size, bool ro, bool random)
        {
            (void)addr; (void)size; (void)ro; (void)random;
        }
    """)
    _write(include_dir / "system.h", """
        #define CONFIG_CLOCK_FREQUENCY 100000000
        #define SPIRAM_MODULE_NAME     "model"
        static inline void invd_cpu_dcache_range(void *addr, unsigned int size) { (void)addr; (void)size; }
        static inline void flush_l2_cache(void) {}
    """)
    source = tmp_path / "harness.c"
    _write(source, f"""
        #include <stdbool.h>
        #include <stdint.h>
        #include "{REPO}/litex/soc/software/liblitespi/spiram.c"

        int main(void)
        {{
            return spiram_freq_init();
        }}
    """)
    # Lowest working divisor 3: the clock generator rounds it up to 4, SCK = 100 MHz/4 = 25 MHz.
    assert _run(tmp_path, source) == "SPI RAM clk configured to 25 MHz (div: 3)\n"
