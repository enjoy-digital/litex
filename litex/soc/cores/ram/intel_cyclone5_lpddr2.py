import os
import shutil
import subprocess

from migen import *
from migen.genlib.cdc import MultiReg
from migen.genlib.resetsync import AsyncResetSynchronizer

from litex.gen import *

from litex.soc.interconnect import wishbone
from litex.soc.interconnect.csr import *
from litex.soc.interconnect.avalon import Wishbone2AvalonMM

# Cyclone V LPDDR2 ---------------------------------------------------------------------------------

class CycloneVLPDDR2(LiteXModule):
    """LPDDR2 on the Cyclone V Hard Memory Controller (HMC) behind a 32-bit Wishbone slave.

    The UniPHY/HMC IP (generated by generate_ip with Quartus ip-generate) provides the lpddr2
    clock domain (afi_half_clk): the Wishbone bus is crossed to it and each access is done as a
    single Avalon-MM transfer on the first port of the Multi-Port Front End. Accesses wait for
    the calibration and return an error when it failed.

    The memory is described by its geometry (row_bits, col_bits, bank_bits, DQ width from the
    pads) and by ip_parameters: the other parameters of the IP that differ from its defaults
    (memory timings, ...). Only the first rank is used.
    """
    def __init__(self, platform, pads, rzq, ref_clk, ref_clk_freq, mem_clk_freq,
        speedgrade,
        row_bits,
        col_bits,
        bank_bits,
        reset_n        = 1,
        ip_name        = "cyclonev_lpddr2",
        ip_parameters  = None,
        io_assignments = (
            "OUTPUT_TERMINATION \"SERIES 34 OHM WITH CALIBRATION\"",
            "PACKAGE_SKEW_COMPENSATION OFF",
        )):
        self.platform    = platform
        self.ip_name     = ip_name
        self.bus         = wishbone.Interface(data_width=32, address_width=32)
        self.calibration = CSRStatus(fields=[
            CSRField("init_done",   size=1, description="HMC initialization done."),
            CSRField("cal_success", size=1, description="Calibration success."),
            CSRField("cal_fail",    size=1, description="Calibration failure."),
        ])

        # # #

        # Parameters.
        dq_width      = len(pads.dq)
        self.size     = 2**(row_bits + col_bits + bank_bits)*dq_width//8
        address_width = log2_int(self.size//(32//8))

        # IP Parameters (Hard PHY/Controller, full rate, a 32-bit Avalon-MM port).
        self.ip_parameters = {
            "HARD_EMIF"           : "true",
            "HARD_PHY"            : "true",
            "RATE"                : "Full",
            "SPEED_GRADE"         : speedgrade,
            "MEM_CLK_FREQ"        : mem_clk_freq/1e6,
            "REF_CLK_FREQ"        : ref_clk_freq/1e6,
            "MEM_DQ_WIDTH"        : dq_width,
            "MEM_ROW_ADDR_WIDTH"  : row_bits,
            "MEM_COL_ADDR_WIDTH"  : col_bits,
            "MEM_BANKADDR_WIDTH"  : bank_bits,
        }
        self.ip_parameters.update({} if ip_parameters is None else ip_parameters)
        self.ip_parameters.update({
            "AVL_DATA_WIDTH_PORT" : "32 32 32 32 32 32",
            "EXPORT_AFI_HALF_CLK" : "true",
            "USER_DEBUG_LEVEL"    : 0,
        })

        # Clocking / Reset (Power-on reset on ref_clk, lpddr2 domain from the HMC).
        self.cd_lpddr2_por = ClockDomain("lpddr2_por", reset_less=True)
        self.cd_lpddr2     = ClockDomain("lpddr2")
        por            = Signal(4, reset_less=True)
        reset_released = Signal(reset_less=True, name="lpddr2_por_done")
        afi_reset_n    = Signal()
        self.comb += self.cd_lpddr2_por.clk.eq(ref_clk)
        self.sync.lpddr2_por += If(~reset_released,
            por.eq(por + 1),
            reset_released.eq(por == 15),
        )
        self.specials += AsyncResetSynchronizer(self.cd_lpddr2, ~afi_reset_n)

        # Wishbone Clock Domain Crossing (sys -> lpddr2).
        local_bus = wishbone.Interface(data_width=32, address_width=32)
        self.cdc  = wishbone.ClockDomainCrossing(self.bus, local_bus, cd_to="lpddr2")

        # Calibration Status (lpddr2 -> sys).
        init       = Signal()
        success    = Signal()
        fail       = Signal()
        cal_status = Signal(3)
        cal_meta   = Signal(3, name="lpddr2_status_meta", attr={"no_retiming"})
        status     = Signal(3)
        self.sync.lpddr2 += [
            cal_meta.eq(Cat(init, success, fail)),
            cal_status.eq(cal_meta),
        ]
        self.specials += MultiReg(cal_status, status)
        self.comb += [
            self.calibration.fields.init_done.eq(status[0]),
            self.calibration.fields.cal_success.eq(status[1]),
            self.calibration.fields.cal_fail.eq(status[2]),
        ]

        # Wishbone -> Avalon-MM (Error when the calibration failed, wait while it is not done).
        self.bridge = bridge = ClockDomainsRenamer("lpddr2")(Wishbone2AvalonMM(
            data_width           = 32,
            avalon_address_width = address_width,
        ))
        avl = bridge.w2a_avl
        self.comb += [
            local_bus.connect(bridge.w2a_wb, omit={"cyc", "err"}),
            bridge.w2a_wb.cyc.eq(local_bus.cyc & (cal_status == 0b011)),
            local_bus.err.eq(local_bus.cyc & local_bus.stb & cal_status[2]),
        ]

        # Avalon-MM Burst Begin (First cycle of a transfer, not held while the HMC is not ready).
        ready   = Signal()
        begin   = Signal()
        stalled = Signal()
        self.comb += [
            avl.waitrequest.eq(~ready),
            begin.eq((avl.read | avl.write) & ~stalled),
        ]
        self.sync.lpddr2 += stalled.eq((avl.read | avl.write) & ~ready)

        # Hard Memory Controller (Only the first rank is used).
        port_clk     = self.cd_lpddr2.clk
        port_reset_n = ~self.cd_lpddr2.rst
        cke          = Signal()
        cs_n         = Signal()
        self.comb += [
            pads.cke.eq(cke),
            pads.cs_n.eq(Cat(cs_n, 1)),
        ]
        self.specials += Instance(ip_name,
            # Clk / Rst.
            i_pll_ref_clk                = ref_clk,
            i_global_reset_n             = reset_released & reset_n,
            i_soft_reset_n               = 1,
            o_afi_half_clk               = port_clk,
            o_afi_reset_n                = afi_reset_n,

            # Multi-Port Front End Clk / Rst.
            i_mp_cmd_clk_0_clk           = port_clk,
            i_mp_cmd_reset_n_0_reset_n   = port_reset_n,
            i_mp_rfifo_clk_0_clk         = port_clk,
            i_mp_rfifo_reset_n_0_reset_n = port_reset_n,
            i_mp_wfifo_clk_0_clk         = port_clk,
            i_mp_wfifo_reset_n_0_reset_n = port_reset_n,

            # Calibration.
            i_oct_rzqin                  = rzq,
            o_local_init_done            = init,
            o_local_cal_success          = success,
            o_local_cal_fail             = fail,

            # Avalon-MM.
            o_avl_ready_0                = ready,
            i_avl_burstbegin_0           = begin,
            i_avl_addr_0                 = avl.address,
            i_avl_size_0                 = 1,
            i_avl_read_req_0             = avl.read,
            i_avl_write_req_0            = avl.write,
            i_avl_wdata_0                = avl.writedata,
            i_avl_be_0                   = Mux(avl.write, avl.byteenable, 0b1111),
            o_avl_rdata_valid_0          = avl.readdatavalid,
            o_avl_rdata_0                = avl.readdata,

            # LPDDR2.
            o_mem_ca                     = pads.ca,
            o_mem_ck                     = pads.ck_p,
            o_mem_ck_n                   = pads.ck_n,
            o_mem_cke                    = cke,
            o_mem_cs_n                   = cs_n,
            o_mem_dm                     = pads.dm,
            io_mem_dq                    = pads.dq,
            io_mem_dqs                   = pads.dqs_p,
            io_mem_dqs_n                 = pads.dqs_n,
        )

        # Timing Constraints (The calibration status uses synchronizers and the HMC synchronizes
        # its own global reset; the Wishbone bridge uses asynchronous FIFOs: the clocks of the
        # Wishbone side have to be declared asynchronous to the HMC ones by the design).
        platform.toolchain.additional_sdc_commands += [
            "set_false_path -to [get_registers {*lpddr2_status_meta*}]",
            "set_false_path -from [get_registers {*lpddr2_por_done*}] "
            f"-to [get_registers {{*{ip_name}*|*}}]",
        ]

        # IO Constraints.
        for name in ["ca", "ck_p", "ck_n", "dm", "dq", "dqs_p", "dqs_n", "cke", "cs_n"]:
            pad = getattr(pads, name)
            if len(pad) == 1:
                suffix = ""
            elif name in ["cke", "cs_n"]:
                suffix = "[0]" # Only the first rank is used.
            else:
                suffix = "[*]"
            for assignment in io_assignments:
                platform.add_platform_command(
                    f"set_instance_assignment -name {assignment} -to {{pad}}{suffix}", pad=pad)

    def generate_ip(self, output_dir):
        """Generate the UniPHY/HMC IP with Quartus ip-generate, add it to the platform and return
        its .qip file."""
        # Find ip-generate (from QUARTUS_ROOTDIR or from the Quartus binaries on the PATH).
        quartus_root = os.environ.get("QUARTUS_ROOTDIR")
        if quartus_root is None:
            quartus_map = shutil.which("quartus_map")
            if quartus_map is None:
                raise OSError("Put Quartus on PATH or set QUARTUS_ROOTDIR to generate LPDDR2 IP")
            quartus_root = os.path.dirname(os.path.dirname(os.path.realpath(quartus_map)))
        ip_generate = os.path.join(os.path.realpath(quartus_root), "sopc_builder", "bin", "ip-generate")

        # Output directory.
        output_dir = os.path.realpath(output_dir)
        os.makedirs(output_dir, exist_ok=True)

        # Generate.
        cmd = [
            ip_generate,
            "--component-name=altera_mem_if_lpddr2_emif",
            "--file-set=QUARTUS_SYNTH",
            "--standard-reports",
            f"--part={self.platform.device}",
            f"--output-name={self.ip_name}",
            f"--output-directory={output_dir}",
        ]
        cmd += [f"--component-parameter={name}={value}" for name, value in self.ip_parameters.items()]
        subprocess.run(cmd, cwd=output_dir, check=True)

        # Add to the platform.
        ip = os.path.join(output_dir, f"{self.ip_name}.qip")
        self.platform.add_ip(ip)
        return ip
