"""HyperRAM PHYs for Efinix Titanium (DDIO registers, PLL dynamic phase shift read capture).

- TitaniumHyperRAMPHY    : HyperRAM on GPIOs (ex Ti60 F225 Dev Kit).
- TitaniumSiPHyperRAMPHY : In-package HyperRAM of the F100S3F2 SiPs (Ti35/Ti60), hard HYPERRAM block.
"""

from migen import *

from litex.gen import *

from litex.soc.cores.hyperram.common import HyperRAMPHYInterface

# Titanium HyperRAM PHY ----------------------------------------------------------------------------

class TitaniumHyperRAMPHY(LiteXModule):
    """HyperRAM DDR PHY on Efinix Titanium GPIOs (DDIO).

    Clocks (all at the HyperRAM CK frequency, from the same PLL):
    - `cd_sys`  : Core clock. DQ/RWDS/OE are registered on its falling edge (DDIO), CS#/RST# on its
                  rising edge.
    - `cd_90`   : 90° shifted clock. CK is generated by a DDIO register on its falling edge, so CK
                  edges are centered in the DQ/RWDS output data eyes.
    - `cd_cap`  : Read capture clock (DDIO resync inputs). Its phase sets the read capture point; it
                  can be adjusted at runtime through the PLL dynamic phase shift (`shift_pads`) to
                  calibrate reads.
    """
    def __init__(self, platform, pads,
        cd_sys         = "sys",
        cd_90          = "sys90",
        cd_cap         = "sys_cap",
        shift_pads     = None,
        shift_sel      = None,
        drive_strength = 8):
        from litex.build.efinix.common import gpio_info, add_gpio_block

        dw = len(pads.dq)
        self.phy_if = phy_if = HyperRAMPHYInterface(dq_width=dw, cd_cap=cd_cap)

        # # #

        def add_output(pad, clk, clk_inv, ddio):
            io_name, io_pad, io_prop = gpio_info(platform, pad)
            add_gpio_block(platform, {
                "type"           : "GPIO",
                "mode"           : "OUTPUT",
                "name"           : io_name,
                "location"       : io_pad,
                "properties"     : io_prop,
                "size"           : len(pad),
                "out_reg"        : "DDIO" if ddio else "REG",
                "out_clk_pin"    : clk,
                "out_clk_inv"    : int(clk_inv),
                "drive_strength" : dict(io_prop).get("DRIVE_STRENGTH", str(drive_strength)),
            }, pad)
            if ddio:
                return (platform.add_iface_io(io_name + "_HI", len(pad)),
                        platform.add_iface_io(io_name + "_LO", len(pad)))
            return platform.add_iface_io(io_name, len(pad))

        def add_inout(pad):
            io_name, io_pad, io_prop = gpio_info(platform, pad)
            add_gpio_block(platform, {
                "type"           : "GPIO",
                "mode"           : "INOUT",
                "name"           : io_name,
                "location"       : io_pad,
                "properties"     : list(io_prop) + [("PULL_OPTION", "WEAK_PULLDOWN")],
                "size"           : len(pad),
                "in_reg"         : "DDIO_RESYNC",
                "in_clk_pin"     : ClockSignal(cd_cap),
                "in_clk_inv"     : 0,
                "out_reg"        : "DDIO",
                "out_clk_pin"    : ClockSignal(cd_sys),
                "out_clk_inv"    : 1,
                "oe_reg"         : "REG",
                "drive_strength" : dict(io_prop).get("DRIVE_STRENGTH", str(drive_strength)),
            }, pad)
            return {s: platform.add_iface_io(f"{io_name}_{s}", len(pad))
                for s in ["OUT_HI", "OUT_LO", "OE", "IN_HI", "IN_LO"]}

        # Output timing: CS#/RST# use rising-edge registers (pin updated at the start of the next
        # cycle) while DQ/RWDS/CK DDIO registers sample on falling edges within the cycle: delay
        # DQ/RWDS/CK by one cycle so CS# falls 3/4 of a CK period before the first CK rising edge,
        # and keep CS# low `cs_hold` cycles after the last CK cycle (tCSH and last read word).
        sd = getattr(self.sync, cd_sys)
        ck_en     = Signal()
        dq_o_hi   = Signal(dw)
        dq_o_lo   = Signal(dw)
        dq_oe     = Signal()
        rwds_o_hi = Signal(dw//8)
        rwds_o_lo = Signal(dw//8)
        rwds_oe   = Signal()
        sd += [
            ck_en.eq(phy_if.ck_en),
            dq_o_hi.eq(phy_if.dq_o_hi),
            dq_o_lo.eq(phy_if.dq_o_lo),
            dq_oe.eq(phy_if.dq_oe),
            rwds_o_hi.eq(phy_if.rwds_o_hi),
            rwds_o_lo.eq(phy_if.rwds_o_lo),
            rwds_oe.eq(phy_if.rwds_oe),
        ]
        cs_hold = 2
        cs_n_sr = Signal(cs_hold, reset=2**cs_hold - 1)
        sd += cs_n_sr.eq(Cat(phy_if.cs_n, cs_n_sr))

        # CK (differential or single-ended).
        ck_pads = [pads.clk_p, pads.clk_n] if hasattr(pads, "clk_p") else [pads.clk]
        for i, ck_pad in enumerate(ck_pads):
            ck_hi, ck_lo = add_output(ck_pad, ClockSignal(cd_90), clk_inv=True, ddio=True)
            self.comb += [
                ck_hi.eq(ck_en if i == 0 else ~ck_en),
                ck_lo.eq(0     if i == 0 else 1),
            ]

        # CS#/RST#.
        cs_n  = add_output(pads.cs_n,  ClockSignal(cd_sys), clk_inv=False, ddio=False)
        rst_n = add_output(pads.rst_n, ClockSignal(cd_sys), clk_inv=False, ddio=False)
        self.comb += [
            cs_n.eq(phy_if.cs_n & (cs_n_sr == (2**cs_hold - 1))),
            rst_n.eq(phy_if.rst_n),
        ]

        # DQ/RWDS.
        dq   = add_inout(pads.dq)
        rwds = add_inout(pads.rwds)
        self.comb += [
            dq["OUT_HI"].eq(dq_o_hi),
            dq["OUT_LO"].eq(dq_o_lo),
            dq["OE"].eq(Replicate(dq_oe, dw)),
            rwds["OUT_HI"].eq(rwds_o_hi),
            rwds["OUT_LO"].eq(rwds_o_lo),
            rwds["OE"].eq(Replicate(rwds_oe, dw//8)),
            # DDIO_RESYNC inputs: IN_LO (falling edge) is captured half a cycle before IN_HI
            # (rising edge) of the same cycle, so IN_LO is the first half-word in time.
            phy_if.dq_i_hi.eq(dq["IN_LO"]),
            phy_if.dq_i_lo.eq(dq["IN_HI"]),
            phy_if.rwds_i_hi.eq(rwds["IN_LO"]),
            phy_if.rwds_i_lo.eq(rwds["IN_HI"]),
        ]

        # Capture clock dynamic phase shift.
        self.phase_steps = 0
        if shift_pads is not None:
            self.add_phase_shift(shift_pads, shift_sel)

    def add_phase_shift(self, shift_pads, shift_sel, with_csr=True):
        """Capture clock phase control through the PLL dynamic phase shift.

        `phase` is applied on `phase_load` (SHIFT value held, SHIFT_ENA pulsed). Each step delays
        the capture clock by half a period of the PLL post-divider clock.
        """
        self.phase_steps = 2**len(shift_pads["shift"])
        self.phase       = Signal(len(shift_pads["shift"]))
        self.phase_load  = Signal()

        # # #

        phase     = Signal(len(self.phase))
        shift_ena = Signal()
        timer     = Signal(4)
        self.sync += [
            If(self.phase_load,
                phase.eq(self.phase),
                timer.eq(15),
            ).Elif(timer != 0,
                timer.eq(timer - 1),
            ),
            shift_ena.eq((timer > 4) & (timer < 12)),
        ]
        self.comb += [
            shift_pads["shift"].eq(phase),
            shift_pads["shift_sel"].eq(shift_sel),
            shift_pads["shift_ena"].eq(shift_ena),
        ]

# Titanium SiP HyperRAM PHY ------------------------------------------------------------------------

class TitaniumSiPHyperRAMPHY(TitaniumHyperRAMPHY):
    """HyperRAM DDR PHY for the in-package x16 HyperRAM of the Titanium F100S3F2 SiPs (Ti35/Ti60),
    through the hard HYPERRAM interface block (resource HYPER_RAM0).

    The block has the same DDR register interface as the GPIO DDIO registers (CK_P/N, DQ/RWDS
    OUT_HI/LO, OE, IN_HI/LO, CS_N, RST_N) and three clock inputs, all at the HyperRAM CK frequency
    from the same PLL (as in Efinix's HyperRAM IP example designs):
    - `cd_sys` (CLK)    : Core clock (DQ/RWDS/OE/CS#/RST# registers).
    - `cd_90`  (CLK90)  : 90° shifted clock (CK registers): CK edges centered in the DQ eyes.
    - `cd_cap` (CLKCAL) : Read capture clock, phase calibrated through the PLL dynamic phase shift.

    The block's registers are clocked on rising edges (no clock inversion property, unlike the
    GPIO PHY's falling-edge DQ/CK registers): DQ/CK are half a CK period earlier relative to CS#,
    so they are delayed by `out_delay` (2) cycles (CS# falls 5/4 of a CK period before the first CK
    rising edge, tCSS) and CS# is held `cs_hold` (3) cycles after the last CK cycle.

    250MHz operation needs Efinity 2025.2+ and SiPs with date code 2236 or later (Efinix
    ADV-2511-001); 200MHz otherwise.
    """
    def __init__(self, platform,
        cd_sys     = "sys",
        cd_90      = "sys90",
        cd_cap     = "sys_cap",
        shift_pads = None,
        shift_sel  = None,
        out_delay  = 2,
        cs_hold    = 3,
        name       = "hyperram_sip"):
        from litex.build.efinix import InterfaceWriterBlock
        dw = 16
        self.phy_if = phy_if = HyperRAMPHYInterface(dq_width=dw, cd_cap=cd_cap)

        # # #

        # Block pins (interface IOs).
        pins = {
            "CK_P_HI_PIN"     : ("ck_p_hi",     1),
            "CK_P_LO_PIN"     : ("ck_p_lo",     1),
            "CK_N_HI_PIN"     : ("ck_n_hi",     1),
            "CK_N_LO_PIN"     : ("ck_n_lo",     1),
            "CS_N_PIN"        : ("cs_n",        1),
            "RST_N_PIN"       : ("rst_n",       1),
            "DQ_OUT_HI_PIN"   : ("dq_out_hi",   dw),
            "DQ_OUT_LO_PIN"   : ("dq_out_lo",   dw),
            "DQ_OE_PIN"       : ("dq_oe",       dw),
            "DQ_IN_HI_PIN"    : ("dq_in_hi",    dw),
            "DQ_IN_LO_PIN"    : ("dq_in_lo",    dw),
            "RWDS_OUT_HI_PIN" : ("rwds_out_hi", dw//8),
            "RWDS_OUT_LO_PIN" : ("rwds_out_lo", dw//8),
            "RWDS_OE_PIN"     : ("rwds_oe",     dw//8),
            "RWDS_IN_HI_PIN"  : ("rwds_in_hi",  dw//8),
            "RWDS_IN_LO_PIN"  : ("rwds_in_lo",  dw//8),
        }
        io = {k: platform.add_iface_io(f"{name}_{n}", w) for k, (n, w) in pins.items()}

        # Output registers: DQ/RWDS/OE/CK delayed `out_delay` cycles relative to CS#.
        sd   = getattr(self.sync, cd_sys)
        regs = []
        def delay(sig):
            for _ in range(out_delay):
                sig_d = Signal.like(sig)
                regs.append(sig_d.eq(sig))
                sig = sig_d
            return sig
        ck_en     = delay(phy_if.ck_en)
        dq_o_hi   = delay(phy_if.dq_o_hi)
        dq_o_lo   = delay(phy_if.dq_o_lo)
        dq_oe     = delay(phy_if.dq_oe)
        rwds_o_hi = delay(phy_if.rwds_o_hi)
        rwds_o_lo = delay(phy_if.rwds_o_lo)
        rwds_oe   = delay(phy_if.rwds_oe)
        sd += regs

        # CS# held low `cs_hold` cycles after the last CK cycle (tCSH and last read word).
        cs_n_sr = Signal(cs_hold, reset=2**cs_hold - 1)
        sd += cs_n_sr.eq(Cat(phy_if.cs_n, cs_n_sr))

        self.comb += [
            # CK (differential).
            io["CK_P_HI_PIN"].eq(ck_en),
            io["CK_P_LO_PIN"].eq(0),
            io["CK_N_HI_PIN"].eq(~ck_en),
            io["CK_N_LO_PIN"].eq(1),
            # CS#/RST#.
            io["CS_N_PIN"].eq(phy_if.cs_n & (cs_n_sr == (2**cs_hold - 1))),
            io["RST_N_PIN"].eq(phy_if.rst_n),
            # DQ/RWDS.
            io["DQ_OUT_HI_PIN"].eq(dq_o_hi),
            io["DQ_OUT_LO_PIN"].eq(dq_o_lo),
            io["DQ_OE_PIN"].eq(Replicate(dq_oe, dw)),
            io["RWDS_OUT_HI_PIN"].eq(rwds_o_hi),
            io["RWDS_OUT_LO_PIN"].eq(rwds_o_lo),
            io["RWDS_OE_PIN"].eq(Replicate(rwds_oe, dw//8)),
            # As on the GPIO DDIO resync inputs: IN_LO is the first half-word in time.
            phy_if.dq_i_hi.eq(io["DQ_IN_LO_PIN"]),
            phy_if.dq_i_lo.eq(io["DQ_IN_HI_PIN"]),
            phy_if.rwds_i_hi.eq(io["RWDS_IN_LO_PIN"]),
            phy_if.rwds_i_lo.eq(io["RWDS_IN_HI_PIN"]),
        ]

        # Interface Designer block (clock pin names resolved at generation time: the PLL registers
        # its output clock names in platform.clks).
        pin_names = {k: f"{name}_{n}" for k, (n, w) in pins.items()}
        class SiPHyperRAMBlock(InterfaceWriterBlock):
            def generate(self):
                props = dict(pin_names)
                props["CLK_PIN"]    = platform.clks[cd_sys]
                props["CLK90_PIN"]  = platform.clks[cd_90]
                props["CLKCAL_PIN"] = platform.clks[cd_cap]
                cmds = ["# ---------- HYPERRAM (SiP) ---------",
                        f'design.create_block("{name}", "HYPERRAM")']
                for k, v in props.items():
                    cmds.append(f'design.set_property("{name}", "{k}", "{v}", "HYPERRAM")')
                cmds.append(f'design.assign_resource("{name}", "HYPER_RAM0", "HYPERRAM")')
                cmds.append("# ---------- END HYPERRAM (SiP) ---------\n")
                return "\n".join(cmds)
        platform.toolchain.ifacewriter.blocks.append(SiPHyperRAMBlock(name=name, type="HYPERRAM"))

        # Capture clock dynamic phase shift.
        self.phase_steps = 0
        if shift_pads is not None:
            self.add_phase_shift(shift_pads, shift_sel)
