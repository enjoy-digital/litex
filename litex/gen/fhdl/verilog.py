def _prepare_fragment(f, platform, special_overrides, global_clock_domains=None):
    # Convert to FHDL's fragments if not already done.
    if not isinstance(f, _Fragment):
        f = f.get_fragment()

    # Ensure clock domains are available (hierarchical mode may require global domains).
    if global_clock_domains is not None:
        # Merge global and local clock domains so submodules can use their
        # locally-defined domains (e.g. renamed/derived CDC domains).
        # Globals win name collisions (first occurrence): ClockDomainsRenamer
        # mutates shared ClockDomain objects in place, so local fragments may
        # carry "phantom" domains that merely share a name with the real
        # global domain; the global list's first domain with a given name is
        # authoritative (same first-match semantics as _ClockDomainList
        # lookups in flat conversion).
        merged = {}
        for cd in global_clock_domains:
            if cd.name not in merged:
                merged[cd.name] = cd
        for cd in f.clock_domains:
            if cd.name not in merged:
                merged[cd.name] = cd
        merged_list = _ClockDomainList()
        for cd in merged.values():
            merged_list.append(cd)
        f.clock_domains = merged_list

    # Verify/Create Clock Domains.
    if global_clock_domains is not None:
        # Some wrapped submodules rely on implicit clock domains (e.g. renamed
        # AsyncFIFO write/read). Create missing domains locally to keep ports.
        for cd_name in sorted(list_clock_domains(f)):
            if cd_name not in f.clock_domains:
                f.clock_domains.append(ClockDomain(cd_name))

    for cd_name in sorted(list_clock_domains(f)):
        try:
            f.clock_domains[cd_name]
        except:
            msg = f"""Unresolved clock domain {cd_name}, availables:\n"""
            for f in f.clock_domains:
                msg += f"- {f.name}\n"
            raise Exception(msg)

    # Lower complex slices.
    f = lower_complex_slices(f)

    # Insert resets.
    insert_resets(f)

    # Lower basics.
    f = lower_basics(f)

    # Lower specials.
    if platform is not None:
        for s in f.specials:
            s.platform = platform
    f, lowered_specials = lower_specials(special_overrides, f)

    # Lower complex slices (for complex slices included in specials).
    f = lower_complex_slices(f)

    # Lower basics (for basics included in specials).
    f = lower_basics(f)

    # Lower inout slices only when this can be done without proxy signals.
    f = lower_complex_inout_slices(f)

    return f, lowered_specials


def _resolve_ios(ios, platform):
    """Resolve top-level IOs when not provided explicitly."""
    if len(ios) == 0:
        assert platform is not None
        return platform.constraint_manager.get_io_signals()
    return ios


def _apply_io_name_overrides(ios):
    """Stabilize IO naming from backtrace when no explicit override is set."""
    for io in sorted(ios, key=lambda x: x.duid):
        if io.name_override is None:
            io_name = io.backtrace[-1][0]
            if io_name:
                io.name_override = io_name


def _normalize_hier_path(path):
    """Normalize generated instance names from hierarchy traces."""
    return [p[:-1] if p.endswith("*") else p for p in path]


def _collect_memory_port_signals(specials, clock_domains=None):
    """Collect Memory port interface signals.

    `list_special_ios` does not always include all memory port endpoints.
    This helper gathers them consistently and resolves ClockSignal aliases.
    """
    signals = set()
    targets = set()
    wires   = set()
    for special in specials:
        if not isinstance(special, Memory):
            continue
        for port in special.ports:
            for attr in ["adr", "dat_r", "dat_w", "we", "re", "clk", "clock", "rst"]:
                sig = getattr(port, attr, None)
                if isinstance(sig, ClockSignal) and (clock_domains is not None):
                    sig = clock_domains[sig.cd].clk
                if isinstance(sig, Signal):
                    signals.add(sig)
            # Memory read data is always driven by the memory.
            sig = getattr(port, "dat_r", None)
            if isinstance(sig, ClockSignal) and (clock_domains is not None):
                sig = clock_domains[sig.cd].clk
            if isinstance(sig, Signal):
                targets.add(sig)
                wires.add(sig)
    return signals, targets, wires


def _list_special_ios_from_specials(specials, ins, outs, inouts):
    ios = set()
    for special in specials:
        ios |= special.list_ios(ins, outs, inouts)
    return ios


