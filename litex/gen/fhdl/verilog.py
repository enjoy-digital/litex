def _build_module_tree(top):
    """Build a module ownership tree from LiteX `_submodules`."""

    def _walk(module, parent=None, inst_name=None, path=None, seen=None):
        if seen is None:
            seen = {}
        node = _ModuleNode(module=module, parent=parent, inst_name=inst_name, path=path)
        seen[id(module)] = node
        used_names = set()
        for name, mod in module._submodules:
            if name is None:
                name = allocate_generated_name(mod, used_names)
            elif name in used_names:
                # Duplicate sibling name: migen's _ModuleSubmodules allows
                # registering several submodules under the same name (e.g.
                # liteusb's USBDevice names both of its USBStreamInEndpoint
                # instances "USBStreamInEndpoint"). Disambiguate or the
                # path-derived module names and the instance names in the
                # parent module would collide in the emitted Verilog.
                base = name
                idx  = 2
                name = f"{base}_{idx}"
                while name in used_names:
                    idx += 1
                    name = f"{base}_{idx}"
            used_names.add(name)
            # Avoid emitting shared submodules multiple times. This mirrors
            # Migen's get_fragment_called behavior for shared instances.
            if id(mod) in seen:
                alias = _ModuleNode(module=mod, parent=node, inst_name=name,
                                    path=(path or []) + [name])
                alias.shared_alias = True
                alias.shared_owner = seen[id(mod)]
                node.children.append(alias)
                continue
            child = _walk(mod, parent=node, inst_name=name, path=(path or []) + [name], seen=seen)
            node.children.append(child)
        return node

    return _walk(top, parent=None, inst_name=None, path=[], seen={})


def _get_cd_remaps(module):
    """Return ClockDomainsRenamer mappings stored on a module.

    ClockDomainsRenamer.transform_instance (in migen/fhdl/decorators.py)
    appends each renamer's cd_remapping dict to the module's cd_remap_chain
    list. Nested renamers append in application order (outermost first).
    This replaces closure-introspection with explicit metadata.
    """
    return getattr(module, "cd_remap_chain", [])

