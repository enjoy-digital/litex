def _generate_synchronous_logic(f, ns):
    r = ""
    for k, v in sorted(f.sync.items(), key=itemgetter(0)):
        r += "always @(posedge " + ns.get_name(f.clock_domains[k].clk) + ") begin\n"
        r += _generate_node(ns, AssignType.SIGNAL, 1, v)
        r += "end\n\n"
    return r

