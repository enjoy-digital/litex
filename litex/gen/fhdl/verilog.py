def _convert_hierarchical(f, ios, name, platform, special_overrides, attr_translate, regs_init,
                          comb_cycle_policy, time_unit, time_precision, keep_hierarchy=False):
    """Hierarchical Verilog conversion entry point.

    Builds the module tree, analyzes the hierarchy, partitions modules
    into independent units, and emits one Verilog module per node.
    """
    if LiteXContext.top is None:
        raise ValueError("Hierarchical Verilog generation requires LiteXContext.top to be set.")

    ctx = _HierarchicalBuildContext(
        top               = LiteXContext.top,
        name              = name,
        platform          = platform,
        special_overrides = special_overrides,
        attr_translate    = attr_translate,
        regs_init         = regs_init,
        comb_cycle_policy = comb_cycle_policy,
        time_unit         = time_unit,
        time_precision    = time_precision,
        ios               = _resolve_ios(ios, platform),
        keep_hierarchy    = keep_hierarchy,
    )
    _apply_io_name_overrides(ctx.ios)

    # Prepare global clock domains from the full fragment and build hierarchy.
    ctx.global_clock_domains = f.clock_domains
    ctx.root = _build_module_tree(ctx.top)

    # Phase 1: analysis (populates ctx with per-node data).
    _analyze_hierarchy(ctx)

    # Phase 2: emission (generates Verilog from the populated context).
    verilog = _emit_hierarchy(ctx)

    ctx.conv_output.set_main_source(verilog)
    ctx.conv_output.ns = ctx.ns
    return ctx.conv_output


def convert(f, ios=set(), name="top", platform=None,
    # Verilog parameters.
    special_overrides = dict(),
    attr_translate    = DummyAttrTranslate(),
    regs_init         = True,
    hierarchical      = False,
    comb_cycle_policy = "warn",
    # Sim parameters.
    time_unit      = "1ns",
    time_precision = "1ps",
    ):

    # Build Logic.
    # ------------

    # Convert to FHDL fragment if needed (used by both flat and hierarchical paths).
    if not isinstance(f, _Fragment):
        f = f.get_fragment()
    comb_cycle_policy = _normalize_comb_cycle_policy(comb_cycle_policy)

    # Hierarchical Verilog generation (opt-in path).
    # `hierarchical` may also be a dict of options, e.g.
    # {"enabled": True, "keep_hierarchy": True}; "keep_hierarchy" keeps children
    # as modules by lifting parent-driven child-internal signals to proper
    # input ports instead of inlining the whole child subtree.
    keep_hierarchy = False
    if isinstance(hierarchical, dict):
        keep_hierarchy = bool(hierarchical.get("keep_hierarchy", False))
        hierarchical = bool(hierarchical.get("enabled", True))
    if hierarchical:
        return _convert_hierarchical(
            f                 = f,
            ios               = ios,
            name              = name,
            platform          = platform,
            special_overrides = special_overrides,
            attr_translate    = attr_translate,
            regs_init         = regs_init,
            comb_cycle_policy = comb_cycle_policy,
            time_unit         = time_unit,
            time_precision    = time_precision,
            keep_hierarchy      = keep_hierarchy,
        )

    # Create ConvOutput for flat path.
    r = ConvOutput()

    # Flat Verilog generation.
    f, lowered_specials = _prepare_fragment(
        f=f,
        platform=platform,
        special_overrides=special_overrides,
        global_clock_domains=None
    )

    # IOs collection (when not specified) and naming stabilization.
    ios = _resolve_ios(ios, platform)
    _apply_io_name_overrides(ios)

    # Build Signal Namespace.
    # ----------------------
    ns = build_signal_namespace(
        signals = (
            list_signals(f) |
            list_special_ios(f, ins=True, outs=True, inouts=True) |
            ios
        ),
        reserved_keywords = _ieee_1800_2017_verilog_reserved_keywords
    )
    ns.clock_domains = f.clock_domains

    # Build Verilog.
    # --------------
    verilog = ""

    # Banner.
    verilog += _generate_banner(
        filename     = name,
        device       = getattr(platform, "device", "Unknown"),
        top          = LiteXContext.top.__class__.__name__ if LiteXContext.top is not None else "Unknown",
        hierarchical = False
    )

    # Timescale.
    verilog += _generate_timescale(
        time_unit      = time_unit,
        time_precision = time_precision
    )

    # Module Definition.
    verilog += _generate_separator("Module")
    verilog += _generate_module(f, ios, name, ns, attr_translate)

    # Module Hierarchy.
    verilog += _generate_separator("Hierarchy")
    verilog += _generate_hierarchy(top=LiteXContext.top)

    # Module Signals.
    verilog += _generate_separator("Signals")
    verilog += _generate_signals(f, ios, name, ns, attr_translate, regs_init)

    # Combinatorial Logic.
    verilog += _generate_separator("Combinatorial Logic")
    verilog += _generate_combinatorial_logic(f, ns, comb_cycle_policy)

    # Synchronous Logic.
    verilog += _generate_separator("Synchronous Logic")
    verilog += _generate_synchronous_logic(f, ns)

    # Specials
    verilog += _generate_separator("Specialized Logic")
    verilog += _generate_specials(
        name           = name,
        overrides      = special_overrides,
        specials       = f.specials - lowered_specials,
        namespace      = ns,
        add_data_file  = r.add_data_file,
        attr_translate = attr_translate
    )

    # Module End.
    verilog += "endmodule\n"

    # Trailer.
    verilog += _generate_trailer()

    r.set_main_source(verilog)
    r.ns = ns

    return r
