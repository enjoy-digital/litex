"""The LiteX diagram style, as a small SVG generator.

White canvas, chamfered boxes with a fine grey outline and a soft shadow, light grey fills (darker
for memories and hard blocks), grey orthogonal arrows entering boxes at their centre lines,
Calibri/Carlito text, a caption and the LiteX logo at the bottom. The same style as the historical
LiteX SoC diagrams and the recent USB3-PIPE / TriXium ones (this module is their generator, shared).

A diagram is a script in doc/diagrams/ (see README.md):

    from litex_diagram import *

    def draw(d):
        d.box(10, 10, 200, 80, lines=[("CPU", 17, "bold"), ("VexRiscv", 13)])
        ...
        d.caption(700, 560, "Title", "subtitle")
        d.footer()

    if __name__ == "__main__":
        cli(draw, "my-diagram", 1400, 620, "Title", "Description for screen readers.")

The SVG stays editable by hand (Inkscape or XML); the generator keeps the geometry consistent and
the output byte-deterministic. Layout rules: arrows leave and enter boxes at their centre lines,
boxes of one column share their edges, every label has room between the things it sits between,
with Calibri/Carlito and with the Arial/Liberation Sans fallback (checked by svglint.py). The pages
embed the SVGs; build.py --png exports PNGs for posts and slides.
"""

import argparse
import base64
import os

__all__ = ["Diagram", "cli", "FONT", "MONO", "STROKE", "TEXT", "ARROW", "THICK",
           "MEM", "HARD", "GROUP", "FPGA", "BOARD", "KEY", "WHITE"]

FONT = "Calibri, Carlito, 'Liberation Sans', Arial, Helvetica, sans-serif"
MONO = "'Liberation Mono', Cousine, 'DejaVu Sans Mono', Menlo, Consolas, monospace"   # Terminal captures, bus values.

# Palette: outlines/text/arrows and the box fills, from light (boundaries) to dark (memories).
STROKE, TEXT, ARROW, THICK = "#7f7f7f", "#1a1a1a", "#595959", "#8c8c8c"
WHITE = "#ffffff"   # Regular blocks.
BOARD = "#f8f8f8"   # Outer boundary (board, host, system).
FPGA  = "#e4e4e4"   # FPGA / chip boundary.
GROUP = "#f3f3f3"   # A group of related blocks.
KEY   = "#cdcdcd"   # The blocks the diagram is about.
HARD  = "#dcdcdc"   # Hard blocks (transceivers, PLLs, hard IP).
MEM   = "#c9c9c9"   # Memories and storage.

LOGOS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "logos")

def _esc(s):
    return str(s).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


class Diagram:
    """An SVG canvas of width x height, drawn by calling its methods in z order."""

    def __init__(self, width, height, name, title, desc):
        self.width, self.height, self.name = width, height, name
        self.boxes = []   # (title, x1, y1, x2, y2) of every box, for layouts that need them.
        self.out = [
            f'<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" '
            f'width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" '
            f'aria-labelledby="{name}-title {name}-description">',
            f'  <title id="{name}-title">{_esc(title)}</title>',
            f'  <desc id="{name}-description">{_esc(desc)}</desc>',
            f'  <!-- LiteX diagram style (doc/diagrams/litex_diagram.py). Generated by doc/diagrams/{name}.py; '
            f'edit the script (preferred) or this SVG. -->',
            '  <defs>',
            '    <filter id="shadow" x="-10%" y="-10%" width="125%" height="130%"><feGaussianBlur in="SourceAlpha" '
            'stdDeviation="2.4" result="b"/><feOffset in="b" dx="3" dy="3" result="o"/><feComponentTransfer in="o" '
            'result="s"><feFuncA type="linear" slope="0.32"/></feComponentTransfer><feMerge><feMergeNode in="s"/>'
            '<feMergeNode in="SourceGraphic"/></feMerge></filter>',
            '  </defs>',
            f'  <g id="{name}" font-family="{FONT}">',
            f'  <rect width="{width}" height="{height}" fill="{WHITE}"/>',
        ]

    # Blocks ---------------------------------------------------------------------------------------

    def box(self, x1, y1, x2, y2, fill=WHITE, c=14, lines=(), shadow=True, dash=False):
        """A chamfered box (top-right and bottom-left corners cut by c px) with centred text lines."""
        pts = f"{x1},{y1} {x2-c},{y1} {x2},{y1+c} {x2},{y2} {x1+c},{y2} {x1},{y2-c}"
        extra = ' stroke-dasharray="7,4"' if dash else ""
        filt  = ' filter="url(#shadow)"' if shadow else ""
        self.out.append(f'  <polygon points="{pts}" fill="{fill}" stroke="{STROKE}" stroke-width="1.5"{extra}{filt}/>')
        title = (lines[0][0] if isinstance(lines[0], tuple) else lines[0]) if lines else ""
        self.boxes.append((title, x1, y1, x2, y2))
        if lines:
            self.text_lines((x1 + x2)/2, (y1 + y2)/2, lines)

    def text(self, x, y, t, size=13, anchor="middle", weight=None, style=None, fill=TEXT, rotate=None, family=None):
        """One line of text with its baseline at y. rotate: degrees around (x, y), +-90 for vertical.
        family: another font stack (MONO for terminal text; the spaces are then preserved)."""
        attrs = f'x="{x}" y="{y}" font-size="{size}" text-anchor="{anchor}" fill="{fill}"'
        if weight: attrs += f' font-weight="{weight}"'
        if style:  attrs += f' font-style="{style}"'
        if rotate: attrs += f' transform="rotate({rotate} {x} {y})"'
        if family: attrs += f' font-family="{family}" xml:space="preserve"'
        self.out.append(f'  <text {attrs}>{_esc(t)}</text>')

    def text_lines(self, cx, cy, lines, anchor="middle"):
        """A vertically centred block of lines: str or (text, size, weight, style), weight/style optional."""
        norm = []
        for l in lines:
            l = (l + (None,)*4)[:4] if isinstance(l, tuple) else (l, 13, None, None)
            norm.append((l[0], l[1] or 13, l[2], l[3]))
        heights = [s*1.3 for _, s, _, _ in norm]
        y = cy - sum(heights)/2
        for (t, s, w, st), h in zip(norm, heights):
            self.text(cx, round(y + h*0.5 + s*0.35, 1), t, s, anchor=anchor, weight=w, style=st)
            y += h

    # Connections ----------------------------------------------------------------------------------

    def _head(self, x, y, dx, dy, col, size):
        px, py = -dy, dx
        bx, by = x - dx*size, y - dy*size
        hw = size*0.42
        self.out.append(f'  <polygon points="{x:.1f},{y:.1f} {bx+px*hw:.1f},{by+py*hw:.1f} {bx-px*hw:.1f},{by-py*hw:.1f}" fill="{col}"/>')

    def arrow(self, pts, double=False, thick=False, dash=False):
        """A polyline through pts with an arrow head at the end (and at the start with double).
        thick: a wide data path (4 px), else a control/connection (1.6 px)."""
        col  = THICK if thick else ARROW
        wdt  = 4 if thick else 1.6
        size = 11 if thick else 9
        p = [list(q) for q in pts]
        def unit(a, b):
            dx, dy = b[0]-a[0], b[1]-a[1]
            n = (dx*dx + dy*dy) ** 0.5
            return dx/n, dy/n
        heads = []
        dx, dy = unit(p[-2], p[-1]); heads.append((p[-1][0], p[-1][1], dx, dy))
        p[-1] = [p[-1][0] - dx*(size-2), p[-1][1] - dy*(size-2)]
        if double:
            dx, dy = unit(p[1], p[0]); heads.append((p[0][0], p[0][1], dx, dy))
            p[0] = [p[0][0] - dx*(size-2), p[0][1] - dy*(size-2)]
        d = "M " + " L ".join(f"{x:.1f},{y:.1f}" for x, y in p)
        extra = ' stroke-dasharray="7,4"' if dash else ""
        self.out.append(f'  <path d="{d}" fill="none" stroke="{col}" stroke-width="{wdt}" stroke-linejoin="round"{extra}/>')
        for x, y, dx, dy in heads:
            self._head(x, y, dx, dy, col, size)

    def line(self, x1, y1, x2, y2, col=STROKE, w=1, dash=False):
        extra = ' stroke-dasharray="7,4"' if dash else ""
        self.out.append(f'  <line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{col}" stroke-width="{w}"{extra}/>')

    def dot(self, x, y, r=3.5, col=ARROW):
        """A junction dot where an arrow branches (no arrow head at a junction)."""
        self.out.append(f'  <circle cx="{x}" cy="{y}" r="{r}" fill="{col}"/>')

    # Decorations ----------------------------------------------------------------------------------

    def image(self, path, x, y, w, h):
        """A PNG embedded as base64 (the SVG displays without external assets)."""
        data = base64.b64encode(open(path, "rb").read()).decode()
        self.out.append(f'  <image x="{x}" y="{y}" width="{w}" height="{h}" xlink:href="data:image/png;base64,{data}"/>')

    def caption(self, cx, y, title, *subtitles):
        """The caption under the drawing: a bold italic title and italic lines."""
        self.text(cx, y, title, 26, weight="bold", style="italic")
        for i, s in enumerate(subtitles):
            self.text(cx, y + 29 + 23*i, s, 15, style="italic")

    def footer(self, litex=True, enjoy_digital=False, built_with=False, margin=12):
        """Logos in the bottom corners: LiteX bottom right (with "Built with" for project diagrams),
        Enjoy-Digital bottom left."""
        if enjoy_digital:
            self.image(os.path.join(LOGOS, "enjoy-digital.png"), 18, self.height - 110 - margin, 110, 110)
        if litex:
            w, h = 148, 85
            x, y = self.width - w - margin, self.height - h - margin
            if built_with:
                self.text(x - 8, y + 50, "Built with", 19, anchor="end")
            self.image(os.path.join(LOGOS, "litex.png"), x, y, w, h)

    # Output ---------------------------------------------------------------------------------------

    def svg(self):
        return "\n".join(self.out + ["  </g>", "</svg>"]) + "\n"

    def write(self, path):
        with open(path, "w", encoding="utf-8") as f:
            f.write(self.svg())
        return path


def cli(draw, name, width, height, title, desc, default_out=None):
    """Command line of a diagram script: python3 <name>.py [--out DIR] -> DIR/<name>.svg."""
    if default_out is None:
        default_out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "wiki", "images")
    parser = argparse.ArgumentParser(description=f"{name}: {title}")
    parser.add_argument("--out", default=default_out, help="Output directory (default: doc/wiki/images).")
    args = parser.parse_args()
    d = Diagram(width, height, name, title, desc)
    draw(d)
    path = d.write(os.path.join(args.out, f"{name}.svg"))
    print(path, len(d.svg()), "bytes")
    return path
