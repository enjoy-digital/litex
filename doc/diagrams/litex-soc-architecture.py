"""litex-soc-architecture.svg: the anatomy of a typical LiteX SoC, for the SoC-builder page: the
bus masters (CPU, DMAs, host bridge), the main bus, the memories (ROM, SRAM, LiteDRAM), the CSR
bus and the peripherals with their interrupts, and what sits outside the FPGA.

    python3 doc/diagrams/litex-soc-architecture.py   # -> doc/wiki/images/litex-soc-architecture.svg
"""

from litex_diagram import *

W, H = 1400, 900

DESC = ("A typical LiteX SoC inside an FPGA. The bus masters at the top: the CPU (instruction and "
        "data buses), the DMAs of the cores (LiteEth, LitePCIe, LiteSDCard) and the host bridge "
        "(UARTBone, JTAGBone, Etherbone or PCIe) used by the host tools. They share the main bus, a "
        "Wishbone, AXI-Lite or AXI interconnect (shared bus or crossbar) generated by the SoC builder "
        "from the address map. Its slaves: the ROM holding the BIOS, the SRAM, the main RAM (LiteDRAM "
        "controller driving the DDR chips of the board) and the CSR bridge, which gives access to the "
        "CSR bus. On the CSR bus, every peripheral exposes its control/status registers (UART, timer, "
        "GPIO, SPI/I2C, LiteEth, LiteSDCard, LitePCIe, video, LiteScope...) and the EventManagers "
        "drive the interrupt lines back to the CPU. Outside the FPGA: the serial console and host "
        "bridge, the DDR, the Ethernet PHY, the SD card, the PCIe host.")

def draw(d):
    # FPGA boundary.
    d.box(30, 20, 1370, 700, fill=FPGA, c=30)
    d.text(90, 672, "FPGA", 22, anchor="start", weight="bold", style="italic")
    d.text(90, 690, "LiteX SoC: generated from the target file, sys_clk domain", 13, anchor="start", style="italic")

    # Masters row (y 60..150).
    d.text(715, 48, "Bus masters", 15, weight="bold", style="italic")
    d.box(90, 60, 400, 150, fill=KEY, lines=[("CPU", 18, "bold"), ("VexRiscv · VexiiRiscv · NaxRiscv · Rocket · ...", 13), ("ibus / dbus · interrupts · reset address", 13)])
    d.box(450, 60, 840, 150, lines=[("DMAs of the cores", 16, "bold"), ("LiteEth · LitePCIe · LiteSDCard · LiteSATA · video", 13), ("bus masters for the data transfers", 13)])
    d.box(890, 60, 1340, 150, lines=[("Host bridge", 16, "bold"), ("UARTBone · JTAGBone · Etherbone · PCIe · USB", 13), ("the host tools read and write the whole bus (litex_server)", 13)])
    for x in (245, 645, 1115):
        d.arrow([(x, 150), (x, 210)], double=True, thick=True)

    # Main bus.
    d.box(90, 210, 1340, 270, fill=KEY, c=18, lines=[("Main bus: Wishbone · AXI-Lite · AXI", 18, "bold"),
                                                     ("shared bus or crossbar, 32 to 512-bit, generated from the address map (SoCBusHandler), adapters between standards and widths", 13)])

    # Slaves row (y 330..420).
    for x in (230, 525, 840, 1190):
        d.arrow([(x, 270), (x, 330)], double=True, thick=True)
    d.box(90, 330, 370, 420, fill=MEM, lines=[("ROM", 16, "bold"), ("integrated_rom: the BIOS", 13), ("or SPI flash (LiteSPI, XIP)", 13)])
    d.box(410, 330, 640, 420, fill=MEM, lines=[("SRAM", 16, "bold"), ("integrated_sram", 13), ("stack, BIOS data", 13)])
    d.box(680, 330, 1000, 420, fill=MEM, lines=[("Main RAM", 16, "bold"), ("LiteDRAM controller (add_sdram)", 13), ("or integrated_main_ram, HyperRAM, ...", 13)])
    d.box(1040, 330, 1340, 420, lines=[("CSR bridge", 16, "bold"), ("Wishbone/AXI-Lite to CSR bus", 13), ("csr_data_width 8/32, paging", 13)])

    # CSR bus.
    d.arrow([(1190, 420), (1190, 470)], double=True)
    d.box(90, 470, 1340, 520, fill=GROUP, c=16, lines=[("CSR bus: control/status registers of every core (AutoCSR), one bank per core, addresses in csr.h / csr.csv / csr.svd", 14, "bold")])

    # Peripherals row (y 560..650).
    xs = [(90, 253), (271, 434), (452, 615), (633, 796), (814, 977), (995, 1158), (1176, 1340)]
    labels = [[("UART", 15, "bold"), ("console, crossover", 12), ("IRQ", 12)],
              [("Timer · Watchdog", 14, "bold"), ("GPIO · PWM · LEDs", 12), ("IRQ", 12)],
              [("SPI · I2C · flash", 14, "bold"), ("LiteSPI · LiteI2C", 12), ("IRQ", 12)],
              [("LiteEth MAC", 15, "bold"), ("Ethernet, Etherbone", 12), ("IRQ", 12)],
              [("LiteSDCard · SATA", 13, "bold"), ("storage, DMAs", 12), ("IRQ", 12)],
              [("LitePCIe · Video", 14, "bold"), ("DMA, MSI · framebuffer", 12), ("IRQ", 12)],
              [("LiteScope", 15, "bold"), ("logic analyzer", 12), ("probes", 12)]]
    for (x1, x2), l in zip(xs, labels):
        d.box(x1, 560, x2, 650, lines=l)
        d.arrow([((x1 + x2)/2, 520), ((x1 + x2)/2, 560)], double=True)

    # Interrupts: from the peripherals back to the CPU, along the left side.
    d.arrow([(90, 605), (60, 605), (60, 105), (90, 105)])
    d.text(50, 400, "IRQ lines (EventManager)", 11, style="italic", rotate=-90)

    # Outside the FPGA.
    d.box(90, 730, 370, 790, fill=BOARD, lines=[("Host PC", 15, "bold"), ("serial console · bridge · litex_server", 12)])
    d.box(410, 730, 640, 790, fill=BOARD, lines=[("DDR / SDRAM chips", 15, "bold"), ("DDR3, DDR4, LPDDR4, ...", 12)])
    d.box(680, 730, 1000, 790, fill=BOARD, lines=[("Ethernet PHY · SD card · SATA", 14, "bold"), ("the board connectors", 12)])
    d.box(1040, 730, 1340, 790, fill=BOARD, lines=[("PCIe host · display · sensors", 14, "bold"), ("the board connectors", 12)])
    d.arrow([(230, 700), (230, 730)], double=True)
    d.arrow([(525, 700), (525, 730)], double=True, thick=True)
    d.arrow([(840, 700), (840, 730)], double=True)
    d.arrow([(1190, 700), (1190, 730)], double=True)

    d.footer()

if __name__ == "__main__":
    cli(draw, "litex-soc-architecture", W, H, "Anatomy of a LiteX SoC", DESC)
